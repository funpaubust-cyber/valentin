/**
 * Copy curated portfolio images to public/ and emit src/data/portfolio.ts
 * Run: node scripts/apply-portfolio-selection.mjs
 */
import { readFile, writeFile, mkdir, copyFile } from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const srcDir = path.join(root, "projectphotos");
const publicRoot = path.join(root, "public", "images", "portfolio");
const selectionPath = path.join(__dirname, "portfolio-selection.json");

const GROUP_META = {
  kitchens: { title: "Кухни" },
  hallways: { title: "Прихожие" },
  sofas: { title: "Диваны" },
};

async function optimizeCopy(src, dest) {
  await mkdir(path.dirname(dest), { recursive: true });
  await sharp(src)
    .rotate()
    .resize(1600, 1200, { fit: "inside", withoutEnlargement: true })
    .jpeg({ quality: 86, mozjpeg: true })
    .toFile(dest);
}

async function main() {
  const selection = JSON.parse(await readFile(selectionPath, "utf8"));
  const projectGroups = [];

  for (const [groupId, meta] of Object.entries(GROUP_META)) {
    const collections = selection[groupId];
    const builtCollections = [];

    for (const col of collections) {
      const images = [];
      for (let i = 0; i < col.files.length; i++) {
        const fileName = col.files[i];
        const src = path.join(srcDir, fileName);
        const rel = `/images/portfolio/${groupId}/${col.id}/${String(i + 1).padStart(2, "0")}.jpg`;
        const dest = path.join(root, "public", rel);
        await optimizeCopy(src, dest);
        images.push(rel);
      }

      builtCollections.push({
        id: col.id,
        style: col.style,
        layout: col.layout,
        images,
      });
    }

    projectGroups.push({
      id: groupId,
      title: meta.title,
      cover: builtCollections[0]?.images[0] ?? "",
      collections: builtCollections,
    });
  }

  const ts = `/** Auto-generated by scripts/apply-portfolio-selection.mjs */

export type ProjectGroupId = "kitchens" | "hallways" | "sofas";

export interface PortfolioCollection {
  id: string;
  style: string;
  layout: string;
  images: string[];
}

export interface ProjectGroup {
  id: ProjectGroupId;
  title: string;
  cover: string;
  collections: PortfolioCollection[];
}

export const PORTFOLIO_VERSION = "3";

export const projectGroups: ProjectGroup[] = ${JSON.stringify(projectGroups, null, 2)};
`;

  await writeFile(path.join(root, "src", "data", "portfolio.ts"), ts, "utf8");
  console.log("Wrote src/data/portfolio.ts");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
